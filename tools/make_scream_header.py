"""Turn a scream recording into PumpkinLivePitch/scream_sample.h for the KB2040 version.

    python tools/make_scream_header.py scream.mp3     (needs ffmpeg on PATH)
    python tools/make_scream_header.py --demo        (synthetic placeholder scream)

The sound is stored in the KB2040's flash as 16-bit mono, so no SD card is needed.
While the FSR is held, the sketch repeats a loop section from the loud, steady middle
of the scream. It's found automatically; override it with --loop START END (seconds).
"""
import argparse
import array
import math
import os
import random
import subprocess
import sys

SAMPLE_RATE = 22050
MAX_SECONDS = 5  # about 220 KB; the KB2040 has 8 MB of flash, so this is only a sanity limit
LOOP_FADE = SAMPLE_RATE // 10  # 100 ms crossfade where the loop wraps around
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PumpkinLivePitch", "scream_sample.h")


def decode(path):
    # Leading silence is trimmed so the scream starts the instant the FSR is pressed.
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-vn",
                          "-af", "silenceremove=start_periods=1:start_threshold=-45dB",
                          "-ac", "1", "-ar", str(SAMPLE_RATE), "-f", "s16le", "-"],
                         check=True, capture_output=True).stdout
    samples = array.array("h")
    samples.frombytes(raw[:len(raw) // 2 * 2])
    if sys.byteorder == "big":
        samples.byteswap()
    return list(samples)


def demo():
    # A buzzy, wobbling sawtooth that slides up: close enough to a scream to test with.
    rng = random.Random(1)
    seconds = 1.4
    phase = 0.0
    out = []
    for n in range(int(seconds * SAMPLE_RATE)):
        t = n / SAMPLE_RATE
        freq = (650 + 350 * min(t / 0.3, 1)) * (1 + 0.04 * math.sin(2 * math.pi * 6 * t))
        phase = (phase + freq / SAMPLE_RATE) % 1
        envelope = min(t / 0.02, 1, (seconds - t) / 0.25)
        out.append(envelope * (0.8 * (2 * phase - 1) + 0.2 * rng.uniform(-1, 1)))
    return out


def find_loop(samples):
    # The loud, steady middle: from 100 ms after the scream first gets within 6 dB of its peak
    # level (so the attack plays only once) to the last moment it's still that loud.
    win = SAMPLE_RATE // 20
    levels = [math.sqrt(sum(s * s for s in samples[i:i + win]) / win)
              for i in range(0, len(samples) - win + 1, win)]
    loud = [n for n, level in enumerate(levels) if level >= max(levels) / 2]
    return max((loud[0] + 2) * win, LOOP_FADE), loud[-1] * win


def align_end(samples, start, end):
    # Nudge the loop end by up to 10 ms to where the crossfade best matches the audio
    # just before the loop start, so the two blend instead of partly cancelling out.
    target = samples[start - LOOP_FADE:start]
    candidates = range(max(end - SAMPLE_RATE // 100, start + 2 * LOOP_FADE),
                       min(end + SAMPLE_RATE // 100, len(samples)) + 1)
    return max(candidates, key=lambda e: sum(a * b for a, b in zip(samples[e - LOOP_FADE:e], target)))


def make_loop(samples, start, end):
    # Crossfade the end of the loop into the audio just before its start, so jumping from
    # `end` back to `start` is seamless. Nothing after the loop is ever played, so it's dropped.
    out = samples[:end]
    for k in range(LOOP_FADE):
        t = (k + 1) / LOOP_FADE
        out[end - LOOP_FADE + k] = (out[end - LOOP_FADE + k] * math.sqrt(1 - t)
                                    + samples[start - LOOP_FADE + k] * math.sqrt(t))
    out.append(samples[start])  # the sketch interpolates one sample past the end
    return out


def normalize(samples):
    peak = max(abs(s) for s in samples) or 1
    return [round(s * 0.9 * 32767 / peak) for s in samples]


def write_header(samples, loop_start, source):
    with open(OUT_PATH, "w") as f:
        f.write(f"// Generated by tools/make_scream_header.py from {source}.\n")
        f.write("// Re-run that script to swap in a different scream.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"const uint32_t SCREAM_SAMPLE_RATE = {SAMPLE_RATE};\n")
        f.write(f"const uint32_t SCREAM_LENGTH = {len(samples)};\n")
        f.write(f"const uint32_t SCREAM_LOOP_START = {loop_start};  // replay from here while held\n")
        f.write("const int16_t SCREAM_DATA[SCREAM_LENGTH] = {\n")
        for i in range(0, len(samples), 16):
            f.write("  " + ", ".join(str(s) for s in samples[i:i + 16]) + ",\n")
        f.write("};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", nargs="?", help="scream recording (mp3, wav, ...)")
    parser.add_argument("--demo", action="store_true", help="write a synthetic placeholder scream instead")
    parser.add_argument("--loop", type=float, nargs=2, metavar=("START", "END"),
                        help="section to repeat while held, in seconds after the trimmed start")
    args = parser.parse_args()
    if args.demo == bool(args.source):
        parser.error("give either a recording or --demo")

    samples = (demo() if args.demo else decode(args.source))[:MAX_SECONDS * SAMPLE_RATE]
    if len(samples) < 4 * LOOP_FADE:
        parser.error("not enough audio in the recording")
    if args.loop:
        start, end = (round(s * SAMPLE_RATE) for s in args.loop)
    else:
        start, end = find_loop(samples)
    if start < LOOP_FADE or end - start < 2 * LOOP_FADE or end > len(samples):
        parser.error("the loop must start at least 0.1 s in, last at least 0.2 s and fit in the recording; "
                     "pass --loop START END in seconds")
    end = align_end(samples, start, end)

    write_header(normalize(make_loop(samples, start, end)), start,
                 "a synthetic demo" if args.demo else os.path.basename(args.source))
    print(f"Wrote {end / SAMPLE_RATE:.2f} s of audio to {os.path.normpath(OUT_PATH)}")
    print(f"While held it repeats {start / SAMPLE_RATE:.2f}-{end / SAMPLE_RATE:.2f} s")


if __name__ == "__main__":
    main()
